-- Apply after schema.sql and card-battles.sql, before deploying rating-season code.
-- Rerunnable; season resets are initiated by an administrator through the API.
BEGIN;
CREATE TABLE IF NOT EXISTS public.player_ratings (
  player_id uuid PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  rating integer NOT NULL DEFAULT 1200 CHECK (rating >= 0),
  games_played integer NOT NULL DEFAULT 0 CHECK (games_played >= 0),
  wins integer NOT NULL DEFAULT 0 CHECK (wins >= 0),
  losses integer NOT NULL DEFAULT 0 CHECK (losses >= 0),
  updated_at timestamptz DEFAULT now()
);
ALTER TABLE public.player_ratings ADD COLUMN IF NOT EXISTS draws integer NOT NULL DEFAULT 0 CHECK (draws >= 0);
CREATE INDEX IF NOT EXISTS player_ratings_rating ON public.player_ratings(rating DESC);
CREATE TABLE IF NOT EXISTS public.rating_seasons (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL UNIQUE,
  starts_at timestamptz NOT NULL DEFAULT now(),
  ends_at timestamptz,
  CHECK (ends_at IS NULL OR ends_at > starts_at)
);
CREATE UNIQUE INDEX IF NOT EXISTS rating_seasons_one_active
  ON public.rating_seasons ((ends_at IS NULL)) WHERE ends_at IS NULL;
INSERT INTO public.rating_seasons (name)
  SELECT 'Season 1' WHERE NOT EXISTS (SELECT 1 FROM public.rating_seasons WHERE ends_at IS NULL)
  ON CONFLICT (name) DO NOTHING;
CREATE TABLE IF NOT EXISTS public.player_rating_history (
  season_id bigint NOT NULL REFERENCES public.rating_seasons(id),
  player_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  rating integer NOT NULL CHECK (rating >= 0),
  games_played integer NOT NULL CHECK (games_played >= 0),
  wins integer NOT NULL CHECK (wins >= 0),
  losses integer NOT NULL CHECK (losses >= 0),
  draws integer NOT NULL DEFAULT 0 CHECK (draws >= 0),
  archived_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (season_id,player_id)
);
ALTER TABLE public.card_games ADD COLUMN IF NOT EXISTS player_one_rating integer CHECK (player_one_rating >= 0);
ALTER TABLE public.card_games ADD COLUMN IF NOT EXISTS player_two_rating integer CHECK (player_two_rating >= 0);
CREATE INDEX IF NOT EXISTS player_rating_history_player ON public.player_rating_history(player_id,season_id DESC);
ALTER TABLE public.player_ratings ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.rating_seasons ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.player_rating_history ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.player_ratings,public.rating_seasons,public.player_rating_history FROM PUBLIC;
DO $$ BEGIN
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname='anon') THEN
    REVOKE ALL ON public.player_ratings,public.rating_seasons,public.player_rating_history FROM anon;
  END IF;
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname='authenticated') THEN
    REVOKE ALL ON public.player_ratings,public.rating_seasons,public.player_rating_history FROM authenticated;
  END IF;
END $$;
COMMIT;